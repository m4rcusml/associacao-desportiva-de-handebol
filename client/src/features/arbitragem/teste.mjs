import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";

// Executa os helpers reais com o TypeScript já instalado, sem um runner novo.
const fonte = fs.readFileSync(new URL("../../lib/arbitragem.ts", import.meta.url), "utf8");
const codigo = ts.transpileModule(fonte, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const contexto = { exports: {}, URL };
vm.runInNewContext(codigo, contexto);
const { idJogo, numeroCamisa, podeEstornar, aceitaEvento, aplicarResposta, respostaConfirmada, ultimoLancamento } = contexto.exports;
const id = "d08d7c7c-2133-4292-90e8-e66e83ac80db";
const origem = "https://handebol.test";
for (const entrada of [id, ` ${id.toUpperCase()} `, `/arbitragem/jogos/${id}`, `${origem}/arbitragem/jogos/${id}/`]) assert.equal(idJogo(entrada, origem), id);
for (const entrada of ["", "errado", `/arbitragem/jogos/${id}?senha=segredo`, `/arbitragem/jogos/${id}#token`, `https://outro.test/arbitragem/jogos/${id}`, `//outro.test/arbitragem/jogos/${id}`, `https://usuario:segredo@handebol.test/arbitragem/jogos/${id}`, `/tecnico/jogos/${id}`, `/arbitragem/jogos/${id}/editar`]) assert.equal(idJogo(entrada, origem), null);
for (const [entrada, numero] of [["0", 0], ["0007", 7], ["2147483647", 2147483647]]) assert.equal(numeroCamisa(entrada), numero);
for (const invalido of ["", " ", "-1", "1.5", "1e2", " 1", "+1", "2147483648", "Infinity", "9007199254740993"]) assert.equal(numeroCamisa(invalido), null);
const p = { participacaoId: "p1", inscricaoId: "a", atleta: { id: "atleta1", nomeCompleto: "Ana" }, numeroCamisa: 0, credenciadoEm: "2026-11-10T17:00:00Z", entrouEmQuadraEm: null, escalado: true };
const gol = { id: "l1", participacaoId: "p1", inscricaoId: "a", atleta: p.atleta, numeroCamisa: 0, tipo: "gol", valor: 1, anuladoEm: null, operacaoId: "op1", substituiLancamentoId: null, substituidoPorId: null, registradoEm: "2026-11-10T17:01:00Z", relatorioDisciplinar: null };
assert.equal(ultimoLancamento([]), null);
const golAnterior = { ...gol, id: "anterior", registradoEm: "2026-11-10T16:59:00Z" };
const golAnulado = { ...gol, id: "anulado", registradoEm: "2026-11-10T17:02:00Z", anuladoEm: "2026-11-10T17:03:00Z" };
const recebidosForaDeOrdem = [golAnulado, golAnterior, gol];
assert.equal(ultimoLancamento(recebidosForaDeOrdem), golAnulado, "O último registro anulado continua identificado; Desfazer não migra silenciosamente para outro gol");
assert.equal(recebidosForaDeOrdem[0], golAnulado, "Selecionar Desfazer não reordena os dados oficiais");
assert.equal(ultimoLancamento([{ ...gol, id: "l0" }, gol]), gol, "Empate de horário mantém ordem determinística por ID");
assert.equal(podeEstornar(p, []), true);
assert.equal(podeEstornar({ ...p, entrouEmQuadraEm: "2026-11-10T17:01:00Z" }, []), false);
assert.equal(podeEstornar(p, [gol]), false);
assert.equal(podeEstornar(p, [{ ...gol, anuladoEm: "2026-11-10T17:02:00Z" }]), false, "Anulação não libera estorno pela arbitragem");
assert.equal(podeEstornar(p, [{ ...gol, participacaoId: "outra" }]), true);
const ids = new Set();
assert.equal(aceitaEvento(ids, "9007199254740993"), true);
assert.equal(aceitaEvento(ids, "1"), true, "Commit fora de ordem não pode ser descartado");
assert.equal(aceitaEvento(ids, "9007199254740993"), false);
assert.equal(aceitaEvento(ids, 2), false);
assert.equal(aceitaEvento(ids, ""), false);
for (let i = 0; i < 1000; i++) aceitaEvento(ids, String(i));
assert.equal(ids.size, 256);
const a = { inscricaoId: "a", clube: { id: "clubeA", nome: "Clube A" } };
const b = { inscricaoId: "b", clube: { id: "clubeB", nome: "Clube B" } };
const sessao = { jogo: { id, status: "agendado", clubeA: a, clubeB: b, interrompidoEm: null }, arbitragem: { id: "arb", visualizacao: "linha" }, sessao: { metodoEntrada: "senha" }, podeGerirSenhaPelaConta: false };
const dados = { sessao, atletas: { jogo: { id, status: "agendado" }, clubes: [{ ...a, atletas: [{ atleta: p.atleta, escalado: true, credenciamento: null, impedimento: null }] }, { ...b, atletas: [] }] }, registros: { jogo: { id, status: "agendado" }, lancamentos: [], desempenho: [], placar: null } };
const credenciado = aplicarResposta(dados, { participacao: p, alterado: true });
assert.equal(dados.atletas.clubes[0].atletas[0].credenciamento, null, "O estado anterior é preservado");
assert.equal(credenciado.atletas.clubes[0].atletas[0].credenciamento.numeroCamisa, 0);
const iniciado = aplicarResposta(credenciado, { ...sessao, jogo: { ...sessao.jogo, status: "em_andamento", iniciadoEm: "2026-11-10T17:00:00Z" } });
assert.equal(iniciado.sessao.jogo.status, "em_andamento");
assert.equal(iniciado.atletas.jogo.status, "em_andamento");
const placar = { clubeA: a, clubeB: b, placarClubeA: 1, placarClubeB: 0 };
for (const invalido of [undefined, null, "ok", {}, { alterado: true }]) assert.equal(respostaConfirmada("/lancamentos", invalido), false);
assert.equal(respostaConfirmada("/lancamentos", { lancamento: gol, placar, alterado: true }), true);
assert.equal(respostaConfirmada("/encerramento", { jogo: { id, status: "finalizado", resultado: "normal", vencedor: null }, placar, alterado: false }), true);
assert.equal(respostaConfirmada("/encerramento", { jogo: { id, status: "em_andamento" }, placar, alterado: true }), false);
assert.equal(respostaConfirmada("/credenciamentos", { participacao: p, alterado: true }), true);
assert.equal(respostaConfirmada("/inicio", { ...sessao, alterado: true }), true);
const registrado = aplicarResposta(iniciado, { lancamento: gol, placar });
assert.equal(registrado.registros.placar.placarClubeA, 1);
assert.equal(registrado.registros.desempenho[0].gols, 1);
assert.equal(aplicarResposta(registrado, { lancamento: gol, placar }).registros.lancamentos.length, 1, "Reenvio não duplica o lançamento na tela");
const anulado = { ...gol, anuladoEm: "2026-11-10T17:02:00Z", substituidoPorId: "l2" };
const substituto = { ...gol, id: "l2", tipo: "cartaoVermelho", relatorioDisciplinar: true, substituiLancamentoId: "l1" };
const corrigido = aplicarResposta(registrado, { anulado, lancamento: substituto, placar: { ...placar, placarClubeA: 0 } });
assert.equal(corrigido.registros.lancamentos.length, 2);
assert.equal(corrigido.registros.desempenho[0].gols, 0);
assert.equal(corrigido.registros.desempenho[0].cartoesVermelhos, 1);
assert.equal(corrigido.registros.placar.placarClubeA, 0, "POST oficial deve valer mesmo sem releitura");
assert.equal(podeEstornar(p, corrigido.registros.lancamentos), false);
const novo = { ...p, participacaoId: "p2", atleta: { id: "atleta2", nomeCompleto: "Bia" }, numeroCamisa: 7, escalado: false };
const peloQr = aplicarResposta(iniciado, { participacao: novo });
assert.equal(peloQr.atletas.clubes[0].atletas.length, 2, "Credenciamento por QR pode incluir atleta fora da lista anterior");
const estornado = aplicarResposta(peloQr, { estorno: { atleta: novo.atleta, inscricaoId: "a" } });
assert.equal(estornado.atletas.clubes[0].atletas[1].credenciamento, null);
assert.equal(estornado.atletas.clubes[0].atletas[0].credenciamento.participacaoId, "p1");
console.log("Arbitragem: links, camisas, estorno, eventos fora de ordem, limite de deduplicação e aplicação das respostas oficiais aprovados.");
